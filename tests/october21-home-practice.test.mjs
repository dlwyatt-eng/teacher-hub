import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import test from 'node:test';
const read = async path => JSON.parse(await readFile(new URL(path,import.meta.url),'utf8'));
test('November 23 features fractions and archives the November 16 menu',async()=>{
 const current=await read('../content/home-practice.json');
 const previous=await read('../content/home-practice/2026-11-16.json');
 const manifest=await read('../public/generated/public-window-v2.json');
 for(const field of ['routine','access','stopRule','familyCheck','districtResources']) assert.deepEqual(current[field],previous[field],field);
 assert.equal(previous.week.id,'2026-11-16');
 assert.equal(current.updatedOn,'November 22, 2026');
 assert.equal(current.week.from,'2026-11-23');
 assert.equal(current.week.through,'2026-11-29');
 assert.deepEqual(current.week.featuredIds,['reading','fractions','fairness']);
 assert.deepEqual(current.week.activities.filter(item=>item.id!=='fractions'),previous.week.activities);
 assert.match(current.week.activities.find(item=>item.id==='fractions').check,/5\/3 = 1 2\/3.*2 1\/4 = 9\/4/);
 assert.deepEqual(current.resources.slice(1),previous.resources.slice(1));
 assert.match(current.resources[0].offline,/without a screen/);
 assert.equal(current.week.activities.length,12);
 assert.ok(current.week.featuredIds.every(id=>current.week.activities.some(item=>item.id===id)));
 const math=current.week.activities.find(item=>item.id==='math');
 assert.match(math.example,/1 is not prime/);
 assert.match(math.example,/Keep both 2s/);
 assert.match(math.check,/18 = 2 × 3 × 3/);
 assert.match(math.check,/24 = 2 × 2 × 2 × 3/);
 assert.equal(2*3*3,18);assert.equal(2*2*2*3,24);
 assert.match(current.policy,/optional activity/);
 assert.match(current.unfinished,/Finish only the small piece identified for you/);
 assert.doesNotMatch(current.policy + current.unfinished + current.week.connection,/routine homework|not routinely assigned|not automatically homework/i);
 assert.doesNotMatch(JSON.stringify(manifest),/routine homework|not routinely assigned/i);
 assert.deepEqual(manifest.homePractice,current);
});
