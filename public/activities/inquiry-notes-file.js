'use strict';
// Explicit file selection only. No persistence, network, markup insertion or legacy text parsing.
(() => {
  const fieldIds = ['question', 'countries', 'claim', 'source-a', 'evidence-a', 'source-b', 'evidence-b', 'missing', 'revision', 'next'];
  const checkIds = ['sources-check', 'meaning-check', 'limit-check'];
  const fields = fieldIds.map(id => document.getElementById(id));
  const checks = checkIds.map(id => document.getElementById(id));
  const picker = document.getElementById('notes-file');
  if (!picker || fields.some(field => !field) || checks.some(check => !check)) return;
  const status = document.getElementById('open-status');
  const review = document.getElementById('notes-review');
  const summary = document.getElementById('notes-summary');
  const confirm = document.getElementById('confirm-open');
  const cancel = document.getElementById('cancel-open');
  const open = document.getElementById('open-notes');
  const limit = 12000;
  const maxBytes = 512 * 1024;
  let generation = 0;
  let pending = null;
  function snapshot() {
    return ['inquiry-fieldnotes', 1, fields.map((field, i) => [fieldIds[i], field.value]), checks.map((check, i) => [checkIds[i], check.checked])];
  }
  function validate(data) {
    if (!Array.isArray(data) || data.length !== 4 || data[0] !== 'inquiry-fieldnotes' || data[1] !== 1) throw new Error('format');
    for (const [index, ids] of [[2, fieldIds], [3, checkIds]]) {
      const rows = data[index];
      if (!Array.isArray(rows) || rows.length !== ids.length) throw new Error('fields');
      rows.forEach((row, i) => {
        if (!Array.isArray(row) || row.length !== 2 || row[0] !== ids[i]) throw new Error('field');
        const value = row[1];
        if (index === 3) {
          if (typeof value !== 'boolean') throw new Error('check');
        } else {
          if (typeof value !== 'string' || value.length > limit || /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/.test(value)) throw new Error('text');
          // Browser text inputs strip line breaks. Reject rather than silently lose them.
          if (['question', 'countries', 'next'].includes(ids[i]) && /[\r\n]/.test(value)) throw new Error('line');
          // Textareas normalize CR; only accept the LF form generated by this page.
          if (/\r/.test(value)) throw new Error('line');
        }
      });
    }
    return data;
  }
  function clear() {
    generation++;
    pending = null;
    review.hidden = true;
    cancel.hidden = true;
    picker.value = '';
  }
  function changed() {
    if (pending || !cancel.hidden) {
      clear();
      status.textContent = 'Opening cancelled because you changed your notes. Choose the file again when you are ready.';
    }
  }
  fields.forEach(field => { field.maxLength = limit; field.addEventListener('input', changed); });
  checks.forEach(check => check.addEventListener('change', changed));
  open.addEventListener('click', () => {
    clear();
    status.textContent = 'Choose an editable .json copy. Your current notes will stay until you confirm.';
    picker.click();
  });
  picker.addEventListener('cancel', () => { clear(); status.textContent = 'No file opened. Your current notes are unchanged.'; });
  cancel.addEventListener('click', () => { clear(); status.textContent = 'Opening cancelled. Your current notes are unchanged.'; open.focus(); });
  picker.addEventListener('change', async () => {
    const file = picker.files?.[0];
    clear();
    if (!file) { status.textContent = 'No file opened. Your current notes are unchanged.'; return; }
    const token = generation;
    const before = JSON.stringify(snapshot());
    cancel.hidden = false;
    status.textContent = 'Reading your selected file on this device…';
    try {
      if (!Number.isFinite(file.size) || file.size <= 0 || file.size > maxBytes) throw new Error('size');
      const text = await file.text();
      if (token !== generation) return;
      if (text.length > maxBytes) throw new Error('size');
      const data = validate(JSON.parse(text));
      if (JSON.stringify(snapshot()) !== before) { changed(); return; }
      pending = {data, before};
      const count = data[2].filter(row => row[1].length > 0).length;
      summary.textContent = `${count} of 10 fields contain notes; ${data[3].filter(row => row[1]).length} of 3 checks are selected.\nQuestion: ${data[2][0][1].slice(0, 240) || '(blank)'}\nCountries: ${data[2][1][1].slice(0, 240) || '(blank)'}`;
      review.hidden = false;
      status.textContent = 'File checked. Review the summary before replacing anything.';
      confirm.focus();
    } catch {
      if (token !== generation) return;
      clear();
      status.textContent = 'Could not open this file. Choose an unchanged editable .json copy downloaded from Fieldnotes (version 1, up to 512 KB; each field up to 12,000 characters). Text copies and PDFs cannot reopen. Your current notes are unchanged.';
    }
  });
  confirm.addEventListener('click', () => {
    if (!pending) return;
    if (JSON.stringify(snapshot()) !== pending.before) { changed(); return; }
    const data = pending.data;
    fields.forEach((field, i) => { field.value = data[2][i][1]; });
    checks.forEach((check, i) => { check.checked = data[3][i][1]; });
    clear();
    // Keep the existing conservative leaving warning, including after opening a file.
    fields[0].dispatchEvent(new Event('input', {bubbles: true}));
    status.textContent = 'Saved notes opened. Nothing was uploaded. Download a new editable copy after making changes; this page does not save automatically.';
    fields[0].focus();
  });
  document.getElementById('download-editable').addEventListener('click', () => {
    try {
      const data = validate(snapshot());
      const blob = new Blob([JSON.stringify(data, null, 2) + '\n'], {type: 'application/json'});
      if (blob.size > maxBytes) throw new Error('size');
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url; link.download = 'inquiry-fieldnotes-editable.json';
      document.body.append(link); link.click(); link.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
      status.textContent = 'Editable copy requested. Check your downloads and keep this .json file for next class. The page cannot verify that it saved; your leaving warning stays on.';
    } catch {
      status.textContent = 'Could not request an editable copy. Each field must have at most 12,000 characters and ordinary text. Your notes are unchanged; you can still copy them or print.';
    }
  });
})();
